"""The doc registry: :class:`DocEntry` and how the checks read a repository's list.

A repository's registry is data, its config's ``docs`` (:mod:`.config`), and
pyeye's own is ``docs/facts/docs.toml`` (#1107). Every documentation check
reads that list and nothing else: no check may glob for its own files, so a
file type or tree can't drift out of sight the way the Sphinx ``.rst`` tree did
(#818). ``tests/test_docs_facts_registry.py`` fails if a Markdown file of
pyeye's outside :data:`EXCLUDED_TREES` is missing from it.

Each entry has an audience (``00-documentation-system.md``, D11) and a kind:

- ``prose``: hand-written explanation;
- ``reference``: a page generated by ``scripts/docs_facts.py generate``;
- ``skill``: a skill or skill reference file an agent loads;
- ``history``: a record that must name removed things (C1). Fact blocks still
  apply; the removed-name and prose rules don't.

Paths are repo-relative and POSIX-spelled. The one pattern entry is
``changes/*.md``: changelog fragments come and go with every PR.
"""

from __future__ import annotations

from collections.abc import Iterator, Mapping
from dataclasses import dataclass, field
from fnmatch import fnmatchcase
from pathlib import Path
from types import MappingProxyType
from typing import Literal

Audience = Literal["human", "claude", "both"]
Kind = Literal["prose", "reference", "skill", "history", "record"]


@dataclass(frozen=True)
class DocEntry:
    """One registered documentation file (or, for ``changes/*.md``, pattern).

    Attributes:
        path: Repo-relative POSIX path, or a glob pattern for a churning tree.
        audience: Who reads it (D11).
        kind: How the checks treat it.
        site: Whether the docs site publishes the page (:mod:`.site`). ``None``
            takes the default rule; ``True`` or ``False`` overrides it, on the
            entry itself rather than in a list of its own (design C16).
        allow: Prose-rule ID -> the message of each finding this page may still
            have, one per occurrence (:mod:`.rules`). It only shrinks: ``check``
            fails on a finding not listed and on a listed one no longer found.
        covers: Fact or view IDs the page's prose explains (C3, #826). A view
            stands for its members. Facts shown in the page's marker blocks are
            covered without being listed here.
    """

    path: str
    audience: Audience
    kind: Kind
    allow: Mapping[str, tuple[str, ...]] = field(default_factory=lambda: MappingProxyType({}))
    covers: tuple[str, ...] = ()
    site: bool | None = None

    @property
    def is_pattern(self) -> bool:
        """True for a glob entry (``changes/*.md``)."""
        return any(ch in self.path for ch in "*?[")


#: Historical records: not documentation in scope, never bound or reviewed.
#: Test fixtures are test input, not documentation.
EXCLUDED_TREES: tuple[str, ...] = (
    "docs/superpowers/",
    "docs/decisions/",
    "docs/audits/",
    "tests/fixtures/",
)


def for_repo(root: Path) -> tuple[DocEntry, ...]:
    """*root*'s own doc registry, from its docs-facts config (#1107).

    What a caller that names no registry gets: the analysed repository's, not
    pyeye's. Raises :class:`~.config.ConfigError` if *root* has no valid config.
    """
    from .config import load  # the config module imports this one

    return load(root).docs


def is_excluded(path: str) -> bool:
    """True if *path* (repo-relative, POSIX) is in an excluded history tree."""
    return any(path.startswith(tree) for tree in EXCLUDED_TREES)


def entry_for(path: str, docs: tuple[DocEntry, ...]) -> DocEntry | None:
    """The entry in the registry *docs* for *path*: an exact entry wins over a pattern."""
    for entry in docs:
        if not entry.is_pattern and entry.path == path:
            return entry
    for entry in docs:
        # fnmatch's ``*`` crosses ``/``; a pattern names one directory level only,
        # the level ``registered_files`` globs, so ``changes/sub/x.md`` is unregistered.
        same_depth = path.count("/") == entry.path.count("/")
        if entry.is_pattern and same_depth and fnmatchcase(path, entry.path):
            return entry
    return None


def registered_files(
    root: Path, docs: tuple[DocEntry, ...] | None = None
) -> Iterator[tuple[str, DocEntry]]:
    """Every registered file that exists under *root*, with its entry, in path order.

    A pattern entry expands to its existing matches (with no exact entry of their
    own). A missing exact entry is skipped here; ``check`` reports it. *docs*
    defaults to *root*'s own registry (:func:`for_repo`).
    """
    docs = for_repo(root) if docs is None else docs
    found: dict[str, DocEntry] = {}
    for entry in docs:
        if entry.is_pattern:
            for match in root.glob(entry.path):
                rel = f"{entry.path.rsplit('/', 1)[0]}/{match.name}"
                if entry_for(rel, docs) is entry:
                    found[rel] = entry
        elif (root / entry.path).is_file():
            found[entry.path] = entry
    yield from sorted(found.items())


def missing_files(root: Path, docs: tuple[DocEntry, ...] | None = None) -> list[str]:
    """Exact entries with no file on disk; *docs* defaults to *root*'s own registry."""
    docs = for_repo(root) if docs is None else docs
    return [e.path for e in docs if not e.is_pattern and not (root / e.path).is_file()]

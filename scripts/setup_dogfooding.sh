#!/bin/bash
# Complete setup for dogfooding metrics automation

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

echo "🐕 Setting up PyEye Dogfooding Metrics"
echo "======================================================================"
echo ""

# Check prerequisites
echo "📋 Checking prerequisites..."

# The metrics script imports click and pyeye, which live only in the uv
# environment, so every call goes through uv run (#879).
if ! command -v uv &> /dev/null; then
    echo "❌ uv is required but not installed (https://docs.astral.sh/uv/)"
    exit 1
fi

if ! command -v git &> /dev/null; then
    echo "❌ Git is required but not installed"
    exit 1
fi

if [[ ! -f "$PROJECT_ROOT/scripts/dogfooding_metrics.py" ]]; then
    echo "❌ Dogfooding metrics script not found"
    echo "   Make sure you're running this from the project root"
    exit 1
fi

echo "✅ Prerequisites check passed"
echo ""

# Install git hooks. pre-commit manages them all, including the post-checkout
# hook that starts a metrics session on issue branches (#462). The old
# hand-written hooks overwrote pre-commit's own hook (#578).
echo "🪝 Installing git hooks (pre-commit install)..."
(cd "$PROJECT_ROOT" && uv run --frozen pre-commit install)
echo ""

# Setup shell aliases
echo "🔗 Setting up shell aliases..."
bash "$SCRIPT_DIR/setup_aliases.sh"
echo ""

# Setup grep tracking
echo "🔍 Setting up grep usage tracking..."
bash "$SCRIPT_DIR/setup_grep_tracking.sh"
echo ""

# Create metrics directory
echo "📁 Creating metrics directory..."
mkdir -p "$HOME/.pyeye/metrics"
echo "✅ Metrics directory created: $HOME/.pyeye/metrics"
echo ""

# Test the setup
echo "🧪 Testing setup..."

# Test metrics script
if uv run --frozen --project "$PROJECT_ROOT" python "$PROJECT_ROOT/scripts/dogfooding_metrics.py" --help &> /dev/null; then
    echo "✅ Dogfooding metrics script works"
else
    echo "❌ Dogfooding metrics script failed"
    exit 1
fi

# Test git hooks. Ask git where they are: in a worktree they live in the main
# repository's .git/hooks (or core.hooksPath), not under the worktree's gitdir.
HOOKS_DIR=$(git -C "$PROJECT_ROOT" rev-parse --path-format=absolute --git-path hooks)

if [[ -x "$HOOKS_DIR/post-checkout" ]] && grep -q "File generated by pre-commit" "$HOOKS_DIR/post-checkout"; then
    echo "✅ Git hooks installed and executable"
else
    echo "❌ Git hooks not properly installed"
    exit 1
fi

echo ""
echo "🎉 Dogfooding metrics setup complete!"
echo ""
echo "📊 What happens now:"
echo "   1. When you switch branches: Auto-starts metrics session"
echo "   2. When you use 'grep': Auto-tracks manual search usage"
echo "   3. When you start the next session: Saves the previous one to history"
echo "   4. MCP tool calls: counted by the Claude Code hooks, not here"
echo "      (bash scripts/claude_hooks/setup_mcp_monitoring.sh; see mcp-report)"
echo ""
echo "🔄 To activate shell aliases:"
echo "   source ~/.bashrc  # or ~/.zshrc"
echo ""
echo "🚀 Quick commands:"
echo "   dogfood-start         # Manually start session"
echo "   dogfood-end           # Manually end session"
echo "   dogfood-report        # Report on recent sessions"
echo "   dogfood-saved 10 'reason'  # Log time saved"
echo "   dogfood-bug 'description'  # Log prevented bug"
echo "   (renamed from mcp-*, #982: mcp-report is the Claude Code hooks' report)"
echo ""
echo "📈 To see your metrics:"
echo "   uv run --frozen python scripts/dogfooding_metrics.py report --days 7"
echo ""
echo "Happy dogfooding! 🐕‍🦺"
